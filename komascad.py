def node(parent, tag, **attrs):
    """Add an element in the 3MF model namespace."""
    qualified_tag = "{%s}%s" % (MODEL_NAMESPACE, tag)
    return ET.SubElement(parent, qualified_tag, {k: str(v) for k, v in attrs.items()})


def hex_color(rgba):
    """Format the RGB channels of a 0-1 color as ``#RRGGBB``."""
    return "#" + "".join("%02X" % round(255 * channel) for channel in rgba[:3])


def grid_positions(bounds):
    """Place pieces on a regular grid centerd at the origin.

    Args:
        bounds: One ``(min_x, max_x, min_y, max_y)`` footprint per piece.

    Returns:
        The ``(x, y)`` translation for each piece, filling rows left to right
        from the back. A single piece is left where it is.
    """
    if len(bounds) == 1:
        return [(0.0, 0.0)]
    # A shared cell size keeps the grid regular and guarantees no overlap.
    # The extra margin makes individual pieces easy to click in a slicer.
    margin = 6.0
    cell_width = max(max_x - min_x for min_x, max_x, _, _ in bounds) + margin
    cell_depth = max(max_y - min_y for _, _, min_y, max_y in bounds) + margin
    columns = math.ceil(math.sqrt(len(bounds)))
    rows = math.ceil(len(bounds) / columns)
    positions = []
    for index, (min_x, max_x, min_y, max_y) in enumerate(bounds):
        column, row = index % columns, index // columns
        # Center each piece in its cell, then center the full grid at origin.
        positions.append(((column - (columns - 1) / 2) * cell_width - (min_x + max_x) / 2,
                          ((rows - 1) / 2 - row) * cell_depth - (min_y + max_y) / 2))
    return positions


def create_3mf(destination, pieces, title):
    """Package one or more pieces as a portable multipart color 3MF.

    Every piece is a named object made of aligned material parts. Core
    ``basematerials`` retain human-readable filament names, and one Materials
    and Properties ``colorgroup`` per material gives every mesh an
    object-level color: several FDM slicers treat base materials as display
    only but convert color properties to logical filament assignments. The
    file holds standard geometry and color only, so the slicer stays free to
    choose the printer, filament and process settings.

    Args:
        destination: ``.3mf`` path to write.
        pieces: ``(preset name, parts)`` pairs from ``render_parts``. Repeat
            a pair to place more copies; the copies share one stored mesh but
            are separate named objects. A single piece keeps its coordinates;
            several are spaced on a grid centerd at the origin.
        title: Human-readable model name.

    Returns:
        One ``{"preset", "object_id", "x", "y", "parts"}`` record per placed piece.
    """
    model = ET.Element(
        "{%s}model" % MODEL_NAMESPACE,
        {"unit": "millimeter", "{http://www.w3.org/XML/1998/namespace}lang": "en-US"},
    )
    node(model, "metadata", name="Title").text = title
    node(model, "metadata", name="Application").text = "KomaSCAD " + VERSION
    node(model, "metadata", name="Description").text = (
        "Shogi pieces as separately selectable multipart objects with standard "
        "3MF material and color assignments. Glitter/metallic labels describe "
        "filament choice, not surface textures. No printer, filament, or "
        "slicing settings are embedded."
    )
    resources = node(model, "resources")
    materials = node(resources, "basematerials", id=1)

    # The material key deliberately includes the name: two visually equal
    # swatches may still describe different physical filaments.
    color_groups = {}
    bounds = []
    for preset, parts in pieces:
        xs = [vertex[0] for part in parts for vertex in part[3]]
        ys = [vertex[1] for part in parts for vertex in part[3]]
        bounds.append((min(xs), max(xs), min(ys), max(ys)))
        for _, material, rgba, _, _ in parts:
            key = (material, hex_color(rgba))
            if key not in color_groups:
                color_groups[key] = None
                # Explicit opaque alpha avoids readers that incorrectly
                # interpret a legal six-digit 3MF color as transparent RGBA.
                node(materials, "base", name=material, displaycolor=key[1] + "FF")

    # Separate one-color groups retain compatibility with consumers that do
    # not implement pindex fully.
    next_resource_id = 2
    for key in color_groups:
        color_groups[key] = next_resource_id
        group = ET.SubElement(resources, "{%s}colorgroup" % MATERIAL_NAMESPACE,
                              {"id": str(next_resource_id)})
        ET.SubElement(group, "{%s}color" % MATERIAL_NAMESPACE, {"color": key[1] + "FF"})
        next_resource_id += 1

    build = node(model, "build")
    placed = []
    mesh_ids = {}

    for (preset, parts), (shift_x, shift_y) in zip(pieces, grid_positions(bounds)):
        # A repeated preset reuses the meshes written for its first copy.
        if preset not in mesh_ids:
            mesh_ids[preset] = []
            for role, material, rgba, vertices, faces in parts:
                mesh_ids[preset].append(next_resource_id)
                part_object = node(
                    resources, "object", id=next_resource_id, type="model",
                    name=role.title() + " | " + material,
                    pid=color_groups[(material, hex_color(rgba))], pindex=0,
                )
                next_resource_id += 1
                mesh = node(part_object, "mesh")
                xml_vertices = node(mesh, "vertices")
                xml_faces = node(mesh, "triangles")
                for x, y, z in vertices:
                    node(xml_vertices, "vertex", x=format(x, ".9g"), y=format(y, ".9g"), z=format(z, ".9g"))
                for a, b, c in faces:
                    node(xml_faces, "triangle", v1=a, v2=b, v3=c)

        # Every copy gets its own named object. Bambu Studio turns build items
        # that share one object into unnamed duplicates.
        assembly_id = next_resource_id
        next_resource_id += 1
        assembly = node(resources, "object", id=assembly_id, type="model", name=preset)
        components = node(assembly, "components")
        for object_id in mesh_ids[preset]:
            node(components, "component", objectid=object_id)

        if len(pieces) == 1:
            node(build, "item", objectid=assembly_id)
        else:
            transform = "1 0 0 0 1 0 0 0 1 %s %s 0" % (format(shift_x, ".9g"), format(shift_y, ".9g"))
            node(build, "item", objectid=assembly_id, transform=transform)
        placed.append({
            "preset": preset, "object_id": assembly_id, "x": shift_x, "y": shift_y,
            "parts": [{"part": role, "material": material, "display_color": hex_color(rgba)}
                      for role, material, rgba, _, _ in parts],
        })

    with zipfile.ZipFile(destination, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml", CONTENT_TYPES)
        archive.writestr("_rels/.rels", RELATIONSHIPS)
        archive.writestr("3D/3dmodel.model", ET.tostring(model, encoding="utf-8", xml_declaration=True))
        archive.writestr("Metadata/KomaSCAD.json", json.dumps({
            "version": VERSION, "units": "mm", "pieces": placed,
            "type": "portable multipart model with standard color assignments; no printer settings",
        }, ensure_ascii=False, indent=2))
    return placed


# --- Exporting --------------------------------------------------------------

def per_file(text):
    """Parse ``--per-file``: a positive piece count, or ``all`` for one file."""
    return math.inf if text == "all" else int(text)


def safe_name(name):
    """Convert a preset or set name into a readable cross-platform filename.

    >>> safe_name('Chu Shogi: Lion / Kirin')
    'Chu Shogi - Lion - Kirin'
    """
    cleaned = re.sub(r'[<>:"/\\|?*\x00-\x1f]', " - ", name)
    cleaned = re.sub(r"\s+", " ", cleaned).strip(" .")
    return re.sub(r"(?:\s*-\s*){2,}", " - ", cleaned)


def plan_files(presets, counts, set_name, size):
    """Decide which pieces go into which output file.

    Without ``size`` every preset gets its own file. With it, the full count
    of every preset is split into layout files of at most ``size`` pieces.

    Returns:
        ``(filename, [preset, ...])`` pairs in export order.
    """
    if size:
        # One entry per physical piece, so the layouts hold the full count.
        placements = [preset for preset in presets for _ in range(counts[preset])]
        step = len(placements) if size == math.inf else size
        return [("%s - Layout %02d.3mf" % (safe_name(set_name), number), placements[first:first + step])
                for number, first in enumerate(range(0, len(placements), step), 1)]
    return [(safe_name(preset) + ".3mf", [preset]) for preset in presets]


def describe_pieces(presets):
    """Summarize placed presets for progress output, e.g. ``Pawn x18, King``."""
    counts = {}
    for preset in presets:
        counts[preset] = counts.get(preset, 0) + 1
    return ", ".join(name if count == 1 else "%s x%d" % (name, count) for name, count in counts.items())


def portable_path(path):
    """Describe a source file without revealing where the project is stored.

    Manifests are shared with exported sets, so they must not record a
    maker's home directory or username: files outside the project keep only
    their name.
    """
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return path.name


def sha256_file(path):
    """Calculate a SHA-256 checksum without loading a whole 3MF into memory."""
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def write_manifest(folder, set_name, preset_file, scad, plan, counts, layouts):
    """Record provenance, contents, sizes and checksums of an exported set.

    A layout file lists the presets placed in it; a single-piece file names
    its preset and how many copies a complete set needs.
    """
    files = []
    for filename, members in plan:
        entry = {"file": filename}
        if layouts:
            entry["presets"] = members
        else:
            entry.update(preset=members[0], quantity=counts[members[0]])
        entry.update(bytes=(folder / filename).stat().st_size, sha256=sha256_file(folder / filename))
        files.append(entry)
    document = {
        "format_version": 1,
        "set_name": set_name,
        "source_parameters": portable_path(preset_file),
        "source_scad": portable_path(scad),
        "piece_count": len(counts),
        "total_quantity": sum(counts.values()),
        "files": files,
    }
    (folder / "manifest.json").write_text(
        json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def cmd_export(args):
    """Export chosen presets of one game or preset file as color 3MF files."""
    preset_file = find_preset_file(args.game)
    scad = args.scad.resolve()
    sets, counts = load_parameter_sets(preset_file)
    selected = select_presets(list(sets), args.piece)

    overrides = {parameter: getattr(args, option) for option, (parameter, _) in OVERRIDES.items()
                 if getattr(args, option) is not None}
    if args.signature_text is not None:
        overrides["Signature_Enabled"] = True
    if args.orientation:
        overrides["Print_Orientation"] = ORIENTATIONS[args.orientation]

    set_name = args.name or preset_file.stem.replace("_", " ").replace("-", " ").title()
    destination = (args.output or Path("exports") / preset_file.stem).resolve()
    plan = plan_files(selected, counts, set_name, args.per_file)

    if args.dry_run:
        print(str(destination) + os.sep)
        for filename, members in plan:
            if args.per_file:
                print("  %s  (%d pieces: %s)" % (filename, len(members), describe_pieces(members)))
            else:
                copies = counts[members[0]]
                print("  " + filename + ("" if copies == 1 else "  (print %d)" % copies))
        return 0

    destination.mkdir(parents=True, exist_ok=True)

    exported = skipped = 0
    rendered = {}
    for index, (filename, members) in enumerate(plan, 1):
        output = destination / filename
        progress = "[%d/%d] " % (index, len(plan))
        if output.exists() and not args.force:
            print(progress + "Skipping existing " + filename, flush=True)
            skipped += 1
            continue
        print(progress + "Exporting " + describe_pieces(members), flush=True)
        # Each preset is rendered once, however many copies are placed.
        for preset in members:
            if preset not in rendered:
                if len(set(members)) > 1:
                    print("      rendering " + preset, flush=True)
                rendered[preset] = render_parts(
                    args.openscad, scad, scad_definitions(scad, preset, sets[preset], overrides))
        # A completed file appears under its final name only once it is
        # whole, so an interrupted export is never mistaken for a finished one.
        partial = output.with_name("." + output.name + ".partial")
        try:
            create_3mf(partial, [(preset, rendered[preset]) for preset in members],
                       members[0] if len(members) == 1 else filename[:-4])
            os.replace(partial, output)
        finally:
            if partial.exists():
                partial.unlink()
        exported += 1

    print("Saved %d new 3MF file(s); skipped %d existing in %s" % (exported, skipped, destination))
    # A manifest describes a complete delivery, so a hand-picked subset has none.
    if not args.piece:
        write_manifest(destination, set_name, preset_file, scad, plan, counts, bool(args.per_file))
        print("Manifest: " + str(destination / "manifest.json"))
        if not args.per_file and any(count > 1 for count in counts.values()):
            print("Some pieces are needed more than once; the manifest lists quantities. "
                  "Use --per-file all for the complete set in one file.")
    return 0


# --- Previewing -------------------------------------------------------------

def cmd_preview(args):
    """Render every piece of a game, front and back, onto one HTML page.

    The Customizer shows one preset at a time; this shows a whole set at one
    scale so it can be checked before exporting.
    """
    preset_file = find_preset_file(args.game)
    names = list(load_parameter_sets(preset_file)[0])
    out = (args.output or Path("exports") / "preview" / preset_file.stem).resolve()
    out.mkdir(parents=True, exist_ok=True)

    def render(job):
        name, view, target = job
        status, log = run_openscad([
            args.openscad, "-o", str(target), "--imgsize=" + PREVIEW_SIZE, "--projection=o",
            "--camera=" + PREVIEW_VIEWS[view], "-p", str(preset_file), "-P", name, str(SCAD)])
        if status or not target.exists():
            return "%s (%s): %s" % (name, view, (log.strip().splitlines() or ["no output"])[-1])
        return None

    jobs = [(name, view, out / ("%02d-%s.png" % (index, view)))
            for index, name in enumerate(names, 1) for view in PREVIEW_VIEWS]
    print("Rendering %d pieces from %s ..." % (len(names), shown(preset_file)), flush=True)
    with ThreadPoolExecutor() as pool:
        errors = [error for error in pool.map(render, jobs) if error]
    if errors:
        raise RuntimeError("Render failed:\n  " + "\n  ".join(errors))

    cells = "".join(
        '<figure><img src="%02d-front.png" alt=""><img src="%02d-back.png" alt="">'
        "<figcaption>%s</figcaption></figure>" % (index, index, html.escape(name))
        for index, name in enumerate(names, 1)
    )
    page = (
        '<!doctype html><meta charset="utf-8"><title>%s</title>'
        "<style>body{font-family:sans-serif;margin:16px;background:#fffde7}"
        "main{display:flex;flex-wrap:wrap;gap:8px}figure{margin:0;text-align:center}"
        "img{display:block;width:180px}figcaption{font-size:13px;padding:4px}</style>"
        "<h1>%s</h1><p>Front above, back below. All pieces share one scale.</p><main>%s</main>"
    ) % (html.escape(preset_file.stem), html.escape(preset_file.stem), cells)
    index = out / "index.html"
    index.write_text(page, encoding="utf-8")
    print("Preview: " + str(index))
    return 0


# --- Command line -----------------------------------------------------------

def build_parser():
    """Define every command, its options and its help text in one place."""
    parser = argparse.ArgumentParser(
        description="Build, preview and export 3D-printable shogi pieces.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""\
A GAME is a game name (see '%(prog)s list') or a path to any preset JSON file.

examples:
  %(prog)s list                           show the games
  %(prog)s export shogi --per-file all    the complete set in one color 3MF
  %(prog)s export shogi pawn              just the pawn
  %(prog)s preview minishogi              check a whole set on one page
  %(prog)s build                          after editing presets/pieces/

Run '%(prog)s COMMAND --help' for the options of one command.
""")
    parser.add_argument("-V", "--version", action="version", version="KomaSCAD " + VERSION)
    commands = parser.add_subparsers(dest="command", metavar="COMMAND", title="commands")

    def command(name, run, summary, examples, **options):
        result = commands.add_parser(
            name, help=summary, description=summary[0].upper() + summary[1:] + ".",
            formatter_class=argparse.RawDescriptionHelpFormatter,
            epilog="examples:\n" + examples, **options)
        result.set_defaults(run=run)
        return result

    listing = command("list", cmd_list, "show the games, or the pieces in one game", """\
  %(prog)s            every game and its size
  %(prog)s shogi      the pieces in shogi, with how many a set needs
  %(prog)s -l presets/misc/taikyoku.json
""")
    listing.add_argument("game", nargs="?", metavar="GAME", help="game name or preset JSON file")
    listing.add_argument("-l", "--long", action="store_true", help="also show each piece's category")

    build = command("build", cmd_build, "rebuild the game presets from presets/pieces/", """\
  %(prog)s            rebuild presets/games/ and shogi_piece.json
  %(prog)s --check    exit 1 if they are out of date; write nothing
""")
    build.add_argument("--check", action="store_true",
                       help="exit 1 if any generated file is out of date; write nothing")
    build.add_argument("-f", "--force", action="store_true",
                       help="overwrite shogi_piece.json even if it holds unsaved Customizer edits")

    preview = command("preview", cmd_preview, "render every piece of a game onto one HTML page", """\
  %(prog)s minishogi
  %(prog)s shogi -o /tmp/shogi-preview
""")
    preview.add_argument("game", metavar="GAME", help="game name or preset JSON file")
    preview.add_argument("-o", "--output", type=Path, metavar="DIR",
                         help="output folder (default: exports/preview/GAME)")
    preview.add_argument("--openscad", default="openscad", metavar="PATH", help="OpenSCAD executable")

    export = command("export", cmd_export, "write print-ready color 3MF files", """\
  %(prog)s shogi                        one 3MF per different piece
  %(prog)s shogi --per-file all         the complete 40-piece set in one 3MF
  %(prog)s shogi --per-file 20          the complete set, 20 pieces per 3MF
  %(prog)s shogi pawn king              only the pieces whose names match
  %(prog)s shogi --orientation front-down -o flat
  %(prog)s shogi -n                     show what would be written

Existing files are skipped, so an interrupted export resumes where it
stopped; use --force to write them again.
""")
    export.add_argument("game", metavar="GAME", help="game name or preset JSON file")
    export.add_argument("piece", nargs="*", metavar="PIECE",
                        help="export only pieces whose name is, or contains, this text (default: all)")
    export.add_argument("-o", "--output", type=Path, metavar="DIR",
                        help="folder receiving the 3MF files (default: exports/GAME)")
    export.add_argument("--per-file", type=per_file, metavar="N|all",
                        help="place this many pieces in each 3MF, or 'all' for one file, with as many "
                             "copies of each piece as a complete set needs")
    export.add_argument("--orientation", choices=sorted(ORIENTATIONS),
                        help="how the pieces sit on the bed, overriding the presets: upright stands "
                             "on the heel; front-down and back-down lie flat on that face")
    export.add_argument("-f", "--force", action="store_true",
                        help="overwrite existing 3MF files instead of skipping them")
    export.add_argument("-n", "--dry-run", action="store_true",
                        help="show the files that would be written, without rendering")
    export.add_argument("--name", help="set name used in layout filenames and manifest.json")
    export.add_argument("--scad", type=Path, default=SCAD, metavar="FILE",
                        help="SCAD model to render (default: the bundled shogi_piece.scad)")
    export.add_argument("--openscad", default="openscad", metavar="PATH", help="OpenSCAD executable")
    overrides = export.add_argument_group("overrides for the exported pieces")
    for option, (_, description) in OVERRIDES.items():
        overrides.add_argument("--" + option.replace("_", "-"), metavar="TEXT", help=description)

    setter = command("set", cmd_set, "change a setting across many presets in a hand-kept file", """\
  %(prog)s my.json Base_Width=30 --category 'grid search'
  %(prog)s my.json Front_Relief_Depth=0.30 Back_Relief_Depth=0.30 --all
  %(prog)s my.json 'Front_Glyph_Width=[1.0, 1.1, 1.0]' --preset 'Grid 05' -n

Names are exact Customizer parameter names with underscores. Quote a value
that contains brackets, commas or spaces. For the bundled games, edit
presets/pieces/ and run build instead.
""")
    setter.add_argument("file", type=Path, metavar="FILE", help="Customizer preset JSON file to edit")
    setter.add_argument("assignments", nargs="+", type=assignment, metavar="NAME=VALUE",
                        help="parameter and its new value")
    setter.add_argument("--preset", action="append", default=[], metavar="TEXT",
                        help="select presets whose name contains TEXT; may be repeated")
    setter.add_argument("--category", action="append", default=[], metavar="TEXT",
                        help="select presets whose Category contains TEXT; may be repeated")
    setter.add_argument("--all", action="store_true", help="select every preset in the file")
    setter.add_argument("-n", "--dry-run", action="store_true",
                        help="show the changes without writing the file")
    return parser


def main(argv=None):
    """Run one command; return the process exit status."""
    parser = build_parser()
    args = parser.parse_args(argv)
    if not args.command:
        parser.print_help()
        return 1
    try:
        return args.run(args)
    except (OSError, ValueError, RuntimeError) as error:
        print("%s: error: %s" % (parser.prog, error), file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    sys.exit(main())
