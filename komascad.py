def read_json(path):
    """Parse one JSON file, naming it in any error."""
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise ValueError("Missing file: %s" % shown(path))
    except json.JSONDecodeError as error:
        raise ValueError("Invalid JSON in %s: %s" % (shown(path), error))


# --- Building game presets from the piece files -----------------------------

def face(source, side, style, where):
    """Return the ``style`` settings of one face, or explain what is missing."""
    styles = source.get(side, {})
    if style not in styles:
        raise ValueError("%s has no %s style %r (available: %s)" % (
            where, side, style, ", ".join(styles) or "none"))
    return styles[style]


def build_preset(defaults, piece, filename, front, back):
    """Layer the shared defaults and one piece into a full parameter set.

    Later layers win: common defaults -> front style defaults -> back style
    defaults -> piece body -> piece front style -> piece back style.
    """
    where = "%s.json" % filename
    layers = [
        defaults["common"],
        face(defaults, "front", front, "_defaults.json"),
        face(defaults, "back", back, "_defaults.json"),
        piece.get("body", {}),
        face(piece, "front", front, where),
    ]
    # Kings and golds have no promoted side: their reverse stays blank.
    if "back" in piece:
        layers.append(face(piece, "back", back, where))
    known = set(layers[0]) | set(layers[1]) | set(layers[2]) | {
        "Piece_Length", "Base_Width", "Rear_Thickness", "Tip_Thickness"}
    preset = {}
    for layer in layers:
        unknown = sorted(set(layer) - known)
        if unknown:
            raise ValueError("%s uses unknown parameter(s): %s" % (where, ", ".join(unknown)))
        preset.update(layer)
    return preset


def build_games():
    """Return ``{game: (presets, counts)}`` for every recipe in games.json.

    ``presets`` maps preset names to parameters; ``counts`` maps the same
    names to how many of that piece a complete set needs.
    """
    defaults = read_json(PIECES / "_defaults.json")
    games = {}
    for key, recipe in read_json(RECIPES).items():
        sets, counts = {}, {}
        for number, (filename, count) in enumerate(recipe["pieces"].items(), 1):
            piece = read_json(PIECES / (filename + ".json"))
            preset = build_preset(defaults, piece, filename, recipe["front"], recipe["back"])
            preset["Category"] = "%s / %s" % (recipe["title"], piece["category"])
            name = "%s %02d - %s" % (recipe["title"], number, piece["name"])
            sets[name], counts[name] = preset, count
        games[key] = (sets, counts)
    return games


def render_presets(sets, counts=None):
    """Serialize parameter sets the way the OpenSCAD Customizer saves them.

    ``counts`` adds the ``pieceCounts`` object the export command reads;
    OpenSCAD ignores it.
    """
    document = {"fileFormatVersion": "1", "parameterSets": sets}
    if counts:
        document["pieceCounts"] = counts
    return json.dumps(document, ensure_ascii=False, indent=4, sort_keys=True) + "\n"


def generated_files(games):
    """Return ``{path: text}`` for every file the build command writes."""
    combined = {}
    for sets, _ in games.values():
        duplicate = sorted(set(sets) & set(combined))
        if duplicate:
            raise ValueError("Two games produce the same preset name: " + duplicate[0])
        combined.update(sets)
    outputs = {GAMES / (key + ".json"): render_presets(sets, counts)
               for key, (sets, counts) in games.items()}
    outputs[CUSTOMIZER] = render_presets(combined)
    return outputs


def stale_files(outputs):
    """List generated files that are missing or differ from a fresh build."""
    return [path for path, text in outputs.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text]


def unsaved_edits():
    """List Customizer changes in shogi_piece.json that a rebuild would erase.

    The Customizer saves into shogi_piece.json, which the build regenerates.
    Anything there that differs from the last build exists nowhere else.
    """
    if not CUSTOMIZER.exists():
        return []
    current = read_json(CUSTOMIZER).get("parameterSets", {})
    previous = {}
    for path in sorted(GAMES.glob("*.json")):
        previous.update(read_json(path).get("parameterSets", {}))
    edits = []
    for name, values in current.items():
        if name not in previous:
            edits.append("%s: preset is not in any game file" % name)
            continue
        for parameter in sorted(set(values) | set(previous[name])):
            old, new = previous[name].get(parameter), values.get(parameter)
            if old != new:
                edits.append("%s: %s = %s (built value: %s)" % (name, parameter, new, old))
    return edits


def cmd_build(args):
    """Rebuild the generated preset files, or report which are out of date."""
    games = build_games()
    outputs = generated_files(games)

    if args.check:
        stale = stale_files(outputs)
        for path in stale:
            print("Out of date: %s" % shown(path))
        return 1 if stale else 0

    edits = [] if args.force else unsaved_edits()
    if edits:
        print("shogi_piece.json has Customizer edits that are not in the piece files:\n")
        for edit in edits:
            print("  " + edit)
        raise ValueError("Copy the values you want to keep into presets/pieces/, "
                         "then rerun (or use --force to discard them).")

    GAMES.mkdir(parents=True, exist_ok=True)
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
    for key, (sets, counts) in games.items():
        print("presets/games/%s.json: %d presets, %d pieces in a full set" % (
            key, len(sets), sum(counts.values())))
    print("shogi_piece.json: %d presets (all games, for the Customizer)" % sum(
        len(sets) for sets, _ in games.values()))
    return 0


# --- Reading preset files ---------------------------------------------------

def find_preset_file(text):
    """Resolve a GAME argument: a game name, or a path to any preset JSON."""
    path = Path(text)
    if not path.is_file():
        path = GAMES / (text + ".json")
    if not path.is_file():
        games = sorted(candidate.stem for candidate in GAMES.glob("*.json"))
        close = difflib.get_close_matches(text, games, 1)
        raise ValueError("No game or preset file named %r.%s Games: %s" % (
            text, " Did you mean %r?" % close[0] if close else "", ", ".join(games)))
    path = path.resolve()
    # shogi_piece.json may hold deliberate Customizer edits, so only the
    # per-game files are held to the piece files.
    if path.parent == GAMES and path in stale_files(generated_files(build_games())):
        raise ValueError("%s is older than the piece files. Run '%s build' first."
                         % (shown(path), Path(sys.argv[0]).name))
    return path


def load_parameter_sets(path):
    """Read a Customizer preset file.

    Returns ``(sets, counts)``: the named parameter sets in file order, and
    how many copies of each a complete set needs. Counts come from an
    optional top-level ``pieceCounts`` object; presets it omits count once.
    """
    document = read_json(path)
    sets = document["parameterSets"]
    declared = document.get("pieceCounts", {})
    return sets, {name: declared.get(name, 1) for name in sets}


def select_presets(names, filters):
    """Pick presets by exact name or case-insensitive part of a name.

    No filters selects everything. The result keeps file order.
    """
    if not filters:
        return list(names)
    chosen = set()
    for text in filters:
        matches = [text] if text in names else [
            name for name in names if text.casefold() in name.casefold()]
        if not matches:
            raise ValueError("No piece matches %r. Use the list command to see the names." % text)
        chosen.update(matches)
    return [name for name in names if name in chosen]


def cmd_list(args):
    """Show every game, or the presets inside one game or preset file."""
    if args.game is None:
        rows = [("GAME", "PIECES", "FULL SET")] + [
            (key, str(len(sets)), str(sum(counts.values())))
            for key, (sets, counts) in build_games().items()]
        width = max(len(row[0]) for row in rows)
        for game, pieces, total in rows:
            print("%s  %6s  %8s" % (game.ljust(width), pieces, total))
        return 0
    sets, counts = load_parameter_sets(find_preset_file(args.game))
    for name, values in sets.items():
        line = name if counts[name] == 1 else "%s  x%d" % (name, counts[name])
        if args.long:
            line += "  [%s]" % values.get("Category", "no category")
        print(line)
    return 0


# --- Editing hand-kept preset files -----------------------------------------

def assignment(text):
    """Parse one ``NAME=VALUE`` argument, keeping the value as text."""
    key, separator, value = text.partition("=")
    if not separator:
        raise argparse.ArgumentTypeError("use NAME=VALUE, for example Base_Width=30")
    return key.strip(), value


def cmd_set(args):
    """Apply the same parameter values to a chosen group of presets."""
    path = args.file.resolve()
    document = read_json(path)
    sets = document["parameterSets"]
    names = [text.casefold() for text in args.preset]
    categories = [text.casefold() for text in args.category]
    changes = []
    selected = 0
    for name, values in sets.items():
        category = str(values.get("Category", "")).casefold()
        if not (args.all or any(text in name.casefold() for text in names)
                or any(text in category for text in categories)):
            continue
        selected += 1
        for key, value in args.assignments:
            if key not in values:
                raise ValueError("%r has no parameter %r; check the spelling" % (name, key))
            old = values[key]
            if old != value:
                changes.append("%s: %s: %r -> %r" % (name, key, old, value))
                values[key] = value
    for change in changes:
        print(change)
    if args.dry_run:
        print("Would change %d value(s) in %d selected preset(s); nothing written." % (len(changes), selected))
    elif changes:
        path.write_text(json.dumps(document, ensure_ascii=False, indent=4) + "\n", encoding="utf-8")
        print("Changed %d value(s) in %d selected preset(s) of %s." % (len(changes), selected, shown(path)))
    else:
        print("Nothing to change in %d selected preset(s)." % selected)
    return 0


# --- Running OpenSCAD -------------------------------------------------------

def run_openscad(command):
    """Run OpenSCAD headlessly and return ``(exit status, combined output)``."""
    environment = os.environ.copy()
    if sys.platform.startswith("linux") and not environment.get("DISPLAY"):
        environment.setdefault("QT_QPA_PLATFORM", "offscreen")
    result = subprocess.run(command, capture_output=True, text=True, env=environment)
    return result.returncode, result.stdout + "\n" + result.stderr


@functools.lru_cache(maxsize=None)
def scad_parameters(scad):
    """Return ``(public defaults, hidden names)`` declared in the SCAD source."""
    source = scad.read_text(encoding="utf-8")
    public_source, marker, hidden_source = source.partition("/* [Hidden] */")
    defaults = {
        name: json.loads(value)
        for name, value in re.findall(r"^([A-Za-z_]\w*)\s*=\s*(.+?);", public_source, re.M)
    }
    hidden = set(re.findall(r"^([A-Za-z_]\w*)\s*=", hidden_source if marker else "", re.M))
    return defaults, hidden


def scad_definitions(scad, preset, values, overrides):
    """Turn one saved preset plus overrides into OpenSCAD ``-D`` arguments.

    OpenSCAD 2021.01 preset loading can override -D public parameters, so the
    values are read here and passed explicitly: overrides always win.
    """
    defaults, hidden = scad_parameters(scad)
    typed = {}
    for name, value in values.items():
        # OpenSCAD 2021.01 can leak variables declared after its Hidden marker
        # into a saved preset. They are implementation details, so skip them
        # while still rejecting unknown or misspelled public parameters.
        if name in hidden:
            continue
        if name not in defaults:
            raise ValueError("Preset %r has an unsupported parameter: %s" % (preset, name))
        typed[name] = value if isinstance(defaults[name], str) or not isinstance(value, str) \
            else json.loads(value)
    typed.update(overrides)
    definitions = []
    for name, value in typed.items():
        if name != "Output_Mode":
            definitions.extend(["-D", name + "=" + json.dumps(value, ensure_ascii=False)])
    return definitions


def check_fonts(log):
    """Reject substituted font families when fontconfig tools are present."""
    match = re.search(r'^ECHO: "KOMASCAD_FONTS", (.+)$', log, re.M)
    if not match or not (shutil.which("fc-match") and shutil.which("fc-pattern")):
        return

    generic_families = {"sans", "sans-serif", "serif", "monospace", "system-ui"}
    # OpenSCAD echoes a literal backslash in some registered font family names
    # (for example ``A\-OTF``), while JSON requires that backslash to be
    # escaped. Preserve OpenSCAD's text and make only those literal slashes
    # JSON-safe before decoding the simple string array.
    encoded_fonts = re.sub(r'\\(?!["\\])', r'\\\\', match.group(1))
    for requested in set(json.loads(encoded_fonts)):
        wanted = subprocess.check_output(
            ["fc-pattern", "-f", "%{family}", requested], text=True,
        ).strip()
        actual = subprocess.check_output(
            ["fc-match", "-f", "%{family}", requested], text=True,
        ).strip()
        wanted_families = {family.strip().casefold() for family in wanted.split(",")}
        actual_families = {family.strip().casefold() for family in actual.split(",")}
        if not (wanted_families & actual_families or wanted_families & generic_families):
            raise ValueError(
                'Font "' + requested + '" resolves to "' + actual + '". '
                "Install the intended font or choose its registered family "
                "in your preset before exporting."
            )


def read_stl(path):
    """Read one binary STL and confirm it is a closed mesh.

    Shared coordinates become shared vertex IDs. Each edge must appear in two
    triangles with opposite directions. If independently closed glyph shells
    merely touch along an edge, their vertex IDs are separated without moving
    coordinates; this preserves the exact outline while keeping each shell
    topologically manifold.

    Returns ``(vertices, faces)``: XYZ tuples and triples of vertex indices.
    """
    data = path.read_bytes()
    triangle_count = struct.unpack_from("<I", data, 80)[0]

    vertices = []
    faces = []
    vertex_ids = {}
    for triangle_index in range(triangle_count):
        # A binary triangle stores its normal, three vertices, and two spare bytes.
        values = struct.unpack_from("<12fH", data, 84 + 50 * triangle_index)
        face = []
        for start in (3, 6, 9):
            xyz = tuple(values[start:start + 3])
            if xyz not in vertex_ids:
                vertex_ids[xyz] = len(vertices)
                vertices.append(xyz)
            face.append(vertex_ids[xyz])
        faces.append(face)

    def edge_statistics(mesh_faces):
        statistics = {}
        for a, b, c in mesh_faces:
            for start, end in ((a, b), (b, c), (c, a)):
                edge = (min(start, end), max(start, end))
                count, balance = statistics.get(edge, (0, 0))
                statistics[edge] = (
                    count + 1, balance + (1 if start < end else -1),
                )
        return statistics

    edges = edge_statistics(faces)
    if any(count != 2 or balance != 0 for count, balance in edges.values()):
        # Font outlines can form separate closed extrusions that touch at an
        # exact edge. STL has coordinates but no vertex topology, so global
        # coordinate deduplication makes that edge appear four-sided. Discover
        # shells through ordinary two-face edges, then give touching shells
        # independent IDs at the same coordinates. Truly open or inconsistently
        # wound input still fails the closure check below.
        edge_faces = {}
        face_edges = []
        for face_index, (a, b, c) in enumerate(faces):
            local_edges = []
            for start, end in ((a, b), (b, c), (c, a)):
                edge = (min(start, end), max(start, end))
                edge_faces.setdefault(edge, []).append(face_index)
                local_edges.append(edge)
            face_edges.append(local_edges)

        components = [-1] * len(faces)
        component = 0
        for seed in range(len(faces)):
            if components[seed] != -1:
                continue
            components[seed] = component
            pending = [seed]
            while pending:
                face_index = pending.pop()
                for edge in face_edges[face_index]:
                    incident = edge_faces[edge]
                    if len(incident) != 2:
                        continue
                    other = incident[0] if incident[1] == face_index else incident[1]
                    if components[other] == -1:
                        components[other] = component
                        pending.append(other)
            component += 1

        separated_vertices = []
        separated_faces = []
        separated_ids = {}
        for face_index, face in enumerate(faces):
            separated_face = []
            for vertex_id in face:
                key = (components[face_index], vertex_id)
                if key not in separated_ids:
                    separated_ids[key] = len(separated_vertices)
                    separated_vertices.append(vertices[vertex_id])
                separated_face.append(separated_ids[key])
            separated_faces.append(separated_face)
        vertices, faces = separated_vertices, separated_faces
        edges = edge_statistics(faces)

    if any(count != 2 or balance != 0 for count, balance in edges.values()):
        raise ValueError("Part is not a closed, consistently wound mesh: " + str(path))

    return vertices, faces


def render_parts(executable, scad, definitions):
    """Ask OpenSCAD for every enabled material part of one piece.

    OpenSCAD remains the geometry engine: the meshes are validated and
    packaged, never modified. Returns ``(role, material, rgba, vertices,
    faces)`` tuples in body/front/back/signature order.
    """
    with tempfile.TemporaryDirectory(prefix="komascad-") as temporary:
        folder = Path(temporary)

        # First run: which material parts does this piece have, in which colors?
        echo = folder / "materials.echo"
        status, log = run_openscad(
            [executable, "--hardwarnings", "-o", str(echo)] + definitions
            + ["-D", 'Output_Mode="Color assembly"', "-D", "Export_Metadata=true", str(scad)])
        if echo.exists():
            log += "\n" + echo.read_text(encoding="utf-8")
        if status or "ERROR:" in log or "WARNING:" in log:
            raise RuntimeError("OpenSCAD could not read the piece:\n" + log[-8000:])
        match = re.search(r'^ECHO: "KOMASCAD_EXPORT", (.+)$', log, re.M)
        check_fonts(log)
        enabled = [part[:3] for part in json.loads(match.group(1)) if part[3]]

        # Second run: OpenSCAD animation frames share geometry and CGAL caches,
        # so selecting one output mode per frame renders every part without
        # rebuilding the same piece for body, front, back and signature.
        modes = ["Color " + role for role, _, _ in enabled]
        mode_expression = "%s[min(floor($t*%d),%d)]" % (
            json.dumps(modes, ensure_ascii=False), len(modes), len(modes) - 1)
        output = folder / "part.stl"
        status, log = run_openscad(
            [executable, "--animate", str(len(modes)), "-o", str(output), "--export-format", "binstl"]
            + definitions
            + ["-D", "Output_Mode=" + mode_expression, "-D", "Export_Metadata=false", str(scad)])
        # A direct extrusion can contain independently closed font shells that
        # touch at an exact edge. OpenSCAD warns because STL carries no
        # topology; read_stl() separates their vertex IDs and then performs
        # the strict mesh check. All other OpenSCAD warnings remain fatal.
        allowed = (
            "Object may not be a valid 2-manifold and may need repair",
            "Exported object may not be a valid 2-manifold and may need repair",
        )
        unexpected = [line for line in log.splitlines()
                      if "WARNING:" in line and not any(message in line for message in allowed)]
        if status or "ERROR:" in log or unexpected:
            raise RuntimeError("OpenSCAD could not export color parts:\n" + log[-8000:])

        parts = []
        for index, (role, material, rgba) in enumerate(enabled):
            frame = output.with_name("%s%05d%s" % (output.stem, index, output.suffix))
            parts.append((role, material, rgba) + read_stl(frame))
        return parts


